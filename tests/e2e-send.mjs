// 단어장 ➜ '오늘 학습할 단어로 보내기' + 레벨 Lv.01~Lv.10 표기 검수
// 실행: BASE=http://localhost:4173 node tests/e2e-send.mjs
import { createRequire } from 'module'
const require = createRequire(import.meta.url)
let pw
try { pw = require('playwright') } catch { pw = require('/opt/npm-tools/node_modules/playwright') }
const BASE = process.env.BASE || 'http://localhost:4173'
const id = 'e2e_sd' + Date.now().toString(36)
const results = []
const check = (name, ok, extra = '') => { results.push({ name, ok }); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${extra ? ' — ' + extra : ''}`) }
const browser = await pw.chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 360, height: 780 } })
await ctx.addInitScript(() => { try { localStorage.setItem('foldy.introSeen', '1') } catch {} })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('dialog', (d) => d.accept())
const words = { apple: '사과', happy: '행복한', library: '도서관', orange: '오렌지', school: '학교', banana: '바나나', tiger: '호랑이' }
try {
  await page.goto(BASE)
  await page.getByText('가족 만들기').click()
  await page.getByLabel('가족 이름').fill('보내기')
  await page.getByLabel('가족 아이디').fill(id)
  await page.getByLabel('비밀번호').fill('1234')
  await page.getByLabel('개인정보 처리방침 동의').check()
  await page.getByRole('button', { name: '우리 가족 단어장 만들기' }).click()
  await page.getByRole('button', { name: '저장했어요, 시작하기' }).click()
  await page.getByText('누가 공부할까요?').waitFor()
  const chips = await page.locator('button.chip').allTextContents()
  check('가입 레벨 칩이 Lv.01~Lv.10', chips.filter((t) => /^Lv\.\d\d$/.test(t.trim())).length === 10, chips.join(','))
  check('학생 등급 문구 없음', !(await page.locator('body').textContent()).match(/초1-2|중등|고등|성인/))
  await page.getByLabel('이름', { exact: true }).fill('검수')
  await page.getByRole('button', { name: '추가하기' }).click()
  await page.getByText('안녕, 검수!').waitFor()
  check('홈에 Lv.01 표기', (await page.locator('body').textContent()).includes('Lv.01'))
  const homeTxt = await page.locator('body').textContent()
  check('단어 0개여도 복습·확장 카드가 보임', homeTxt.includes('복습 0개') && homeTxt.includes('확장 0개') && homeTxt.includes('○ 단어부터 열려요'))
  await page.goto(BASE + '/#/add?tab=manual')
  await page.getByText('✍️ 여러 개 한 번에 적기').click()
  await page.getByLabel('한 줄에 하나씩 (영어 뜻)').fill(Object.entries(words).map(([w, m]) => `${w} ${m}`).join('\n'))
  await page.getByRole('button', { name: '아래 목록에 넣기' }).click()
  await page.getByRole('button', { name: /7개 단어장에 넣기/ }).click()
  await page.getByText('7개 담았어요!').waitFor()
  await page.goto(BASE + '/#/book')
  await page.getByRole('button', { name: /오늘 학습할 단어/ }).first().waitFor()
  await page.waitForTimeout(800)
  const sendBtns = await page.getByRole('button', { name: /오늘 학습할 단어로 보내기/ }).count()
  const inBtns = await page.getByRole('button', { name: /오늘 학습할 단어에 있어요/ }).count()
  check('오늘 5개 ✓, 나머지 2개 ➜', inBtns === 5 && sendBtns === 2, `${inBtns}/${sendBtns}`)
  const target = await page.getByRole('button', { name: /오늘 학습할 단어로 보내기/ }).first().getAttribute('aria-label')
  const tw = target.split(' ')[0]
  await page.getByRole('button', { name: new RegExp(`^${tw} 오늘 학습할 단어로 보내기`) }).click()
  await page.getByText(`‘${tw}’ → 오늘의 단어에 넣었어요`).waitFor()
  await page.getByRole('button', { name: new RegExp(`^${tw}: 오늘 학습할 단어에 있어요`) }).waitFor()
  check('보낸 단어가 ✓로 바뀜', true)
  await page.getByText('/ˈhæpi/').waitFor({ timeout: 8000 })
  check('단어장에 발음기호 표시(happy /ˈhæpi/)', true)
  check('발음기호가 단어 수만큼', (await page.locator('.ipa').count()) === 7, String(await page.locator('.ipa').count()))
  await page.screenshot({ path: process.env.SHOT || '/tmp/claude-0/wb.png' })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
  check('360px 가로 넘침 없음', overflow <= 0, String(overflow))
  await page.waitForTimeout(1500)
  await page.evaluate(() => { window.__sawProfiles = false })
  await page.addInitScript(() => {
    const t0 = Date.now()
    const tick = () => { if (document.body && /누가 공부할까요|가족 만들기/.test(document.body.innerText)) localStorage.setItem('e2e.flash', '1'); if (Date.now() - t0 < 4000) requestAnimationFrame(tick) }
    requestAnimationFrame(tick)
  })
  await page.reload()
  await page.getByRole('button', { name: new RegExp(`^${tw}: 오늘 학습할 단어에 있어요`) }).waitFor({ timeout: 8000 })
  check('새로고침 뒤에도 유지(저장됨)', true)
  await page.waitForTimeout(1500)
  check('새로고침 때 로그인·프로필 화면이 비치지 않음', !(await page.evaluate(() => localStorage.getItem('e2e.flash'))))
  await page.goto(BASE + '/#/study')
  await page.getByText('오늘의 단어 6개').waitFor({ timeout: 8000 })
  check('학습 화면 오늘의 단어 6개', true)
  await page.goto(BASE + '/#/')
  await page.getByRole('progressbar').waitFor({ timeout: 8000 })
  check('홈 레벨업 게이지(Lv.01 · 0/90)', (await page.getByRole('progressbar').getAttribute('aria-valuemax')) === '90' && (await page.locator('body').textContent()).includes('0/90'))
  await page.screenshot({ path: (process.env.SHOT || '/tmp/claude-0/x.png').replace('.png', '-home.png') })
  await page.goto(BASE + '/#/quiz/ko')
  await page.getByPlaceholder('한글 뜻').waitFor()
  const prog = (await page.locator('header, .sticky').first().textContent()).match(/(\d+)\/(\d+)/)
  check('퀴즈도 6문제', prog && prog[2] === '6', prog?.[0])
  const qw = (await page.locator('.card p.font-title').first().textContent()).trim()
  const ans = { apple: '사과', happy: '행복한', library: '도서관', orange: '오렌지', school: '학교', banana: '바나나', tiger: '호랑이', webcam: '웹캠' }[qw]
  await page.getByPlaceholder('한글 뜻').fill(ans); await page.keyboard.press('Enter')
  await page.waitForTimeout(1500)
  await page.goto(BASE + '/#/')
  await page.getByText('1/90').waitFor({ timeout: 8000 }).catch(() => {})
  check('퀴즈 하나 맞히면 게이지 1 XP', (await page.locator('body').textContent()).includes('1/90'))
  await page.goto(BASE + '/#/me')
  await page.getByText('레벨 진단하기').waitFor()
  const meTxt = await page.locator('body').textContent()
  check('내 정보 레벨 Lv.01~Lv.10', ['Lv.01', 'Lv.05', 'Lv.10'].every((x) => meTxt.includes(x)))
  check('관리자 아님 → 수정요청 알림 문구 없음', !meTxt.includes('관리자라서'))
} catch (e) { check('실행 중 오류', false, e.message.split('\n').slice(0,3).join(' / ')); await page.screenshot({ path: process.env.SHOT || '/tmp/claude-0/sd.png' }) }
check('페이지 오류 없음', errors.length === 0, errors.join(' | '))
await browser.close()
console.log(`\n${results.filter((r) => r.ok).length}/${results.length} 통과 · 가족 ${id}`)
